"""
Journal entry models with encryption.
"""

import uuid

from django.conf import settings
from django.db import models

from shared.encryption import decrypt_content, encrypt_content


class JournalEntry(models.Model):
    """
    Encrypted journal entry tied to a user and optionally a reading plan day.
    """

    MOOD_CHOICES = [
        ("grateful", "Grateful"),
        ("struggling", "Struggling"),
        ("convicted", "Convicted"),
        ("peaceful", "Peaceful"),
        ("fired_up", "Fired Up"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="journal_entries",
    )
    date = models.DateField()
    plan_enrollment = models.ForeignKey(
        "plans.UserPlanEnrollment",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="journal_entries",
    )
    plan_day = models.ForeignKey(
        "plans.ReadingPlanDay",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="journal_entries",
    )
    focus_intention = models.ForeignKey(
        "reflections.FocusIntention",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="journal_entries",
    )
    focus_themes = models.JSONField(default=list, blank=True)
    encrypted_content = models.BinaryField()
    reflection_prompts_used = models.JSONField(default=list, blank=True)
    mood_tag = models.CharField(max_length=20, choices=MOOD_CHOICES, blank=True)
    is_private = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "journal_entries"
        ordering = ["-date", "-created_at"]

    def __str__(self):
        return f"JournalEntry({self.id}) - {self.date}"

    def set_content(self, content: str):
        """Encrypt and store content."""
        self.encrypted_content = encrypt_content(content, self.user.encryption_key_salt)

    def get_content(self) -> str:
        """Decrypt and return content."""
        if not self.encrypted_content:
            return ""
        return decrypt_content(
            bytes(self.encrypted_content), self.user.encryption_key_salt
        )

    @property
    def content(self):
        return self.get_content()


class JournalFeedback(models.Model):
    """
    The response a journal entry received: a reflection, one scripture passage
    and the full record of why that passage was chosen (the audit log).

    Everything derived from what the person wrote is encrypted with their key.
    The verse text is public scripture fetched from a Bible source — it is
    never written by a model. Regenerating keeps the earlier record
    (is_current=False) so the audit log shows every decision ever made.
    """

    STATUS_CHOICES = [
        ("ok", "Generated by AI"),
        ("fallback", "AI unavailable - built-in rules"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="journal_feedback",
    )
    entry = models.ForeignKey(
        JournalEntry, on_delete=models.CASCADE, related_name="feedback_records"
    )
    is_current = models.BooleanField(default=True)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default="ok")
    is_spiritual = models.BooleanField(default=False)

    # Scripture (public text, from the Bible source)
    scripture_reference = models.CharField(max_length=100, blank=True)
    scripture_book = models.CharField(max_length=50, blank=True)
    scripture_chapter = models.PositiveIntegerField(null=True, blank=True)
    scripture_verse_start = models.PositiveIntegerField(null=True, blank=True)
    scripture_verse_end = models.PositiveIntegerField(null=True, blank=True)
    scripture_text = models.TextField(blank=True)
    scripture_translation = models.CharField(max_length=20, blank=True)
    scripture_source = models.CharField(max_length=20, blank=True)

    # Encrypted JSON: themes, reflection, why_this_passage, meditation_prompt,
    # christlike_step, growth_note, candidates, recent_themes, threads_detected,
    # fallback_reason.
    encrypted_payload = models.BinaryField()

    # Where and how the decision was made (no user text in these).
    provider = models.CharField(max_length=30, blank=True)
    model = models.CharField(max_length=100, blank=True)
    ran_locally = models.BooleanField(default=True)
    provider_source = models.CharField(max_length=10, blank=True)
    prompt_version = models.CharField(max_length=40, blank=True)
    duration_ms = models.PositiveIntegerField(default=0)
    inputs_used = models.JSONField(default=list, blank=True)
    selection_rule = models.CharField(max_length=300, blank=True)

    helpful = models.BooleanField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "journal_feedback"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["user", "-created_at"]),
            models.Index(fields=["entry", "is_current"]),
        ]

    def __str__(self):
        return (
            f"JournalFeedback({self.id}) - {self.scripture_reference or 'no passage'}"
        )

    def set_payload(self, payload: dict):
        import json

        self.encrypted_payload = encrypt_content(
            json.dumps(payload), self.user.encryption_key_salt
        )

    def get_payload(self) -> dict:
        import json

        if not self.encrypted_payload:
            return {}
        return json.loads(
            decrypt_content(
                bytes(self.encrypted_payload), self.user.encryption_key_salt
            )
        )
